import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const parts = ['core','ui','audio','game','storage','input','ai','rules','physics','render','bootstrap'];
let bundle = '/* Generated by tools/build.mjs. Edit src/ and run npm run build. */\n(() => {\n  \'use strict\';\n\n';
for (const name of parts) {
  if (name === 'audio') {
    const samples = Object.fromEntries(['cue','click','clickSoft','rail','pocket'].map((key) =>
      [key, readFileSync(new URL(`lib/audio/${key}.wav`, root)).toString('base64')]));
    bundle += `  const AUDIO_DATA = ${JSON.stringify(samples)};\n\n`;
  }
  bundle += readFileSync(new URL(`src/${name}.js`, root), 'utf8').replace(/\r\n/g, '\n').trimEnd() + '\n\n';
}
bundle += '})();\n';
const target = new URL('lib/client.js', root);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== bundle) throw new Error('Bundle is stale; run npm run build');
  console.log('PASS reproducible bundle and embedded WAV sources');
} else {
  writeFileSync(target, bundle);
  console.log(`Built ${fileURLToPath(target)} (${Buffer.byteLength(bundle)} bytes)`);
}
